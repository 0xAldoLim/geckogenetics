import type { Morph } from './morphs'
import type { ReferenceId } from './references'

const index = (
  name: string,
  category: NonNullable<Morph['category']>,
  note: string,
  refs: ReferenceId[] = ['masterlist'],
  aliases: string[] = [],
): Morph => ({
  name,
  aliases,
  category,
  note,
  refs,
  status:
    category === 'unverified'
      ? 'Name indexed; genetics and lineage unverified'
      : 'Breeder / trade descriptor; no independent gene assumed',
})
const lineNames = (names: string[], refs: ReferenceId[] = ['masterlist']) =>
  names.map((name) =>
    index(
      name,
      'line',
      'A named breeding line or project. Verify the originating breeder and pedigree; this name does not establish hidden alleles or a single-gene inheritance ratio.',
      refs,
    ),
  )
const riskCombo = (name: string): Morph => ({
  name,
  aliases: [],
  category: 'combination',
  risk: 'enigma',
  note: 'A combination name containing Enigma in the referenced nomenclature. Welfare concerns apply; predictions are withheld.',
  refs: ['masterlist', 'enigma'],
  status: 'Breeder combination name; welfare concern',
})

